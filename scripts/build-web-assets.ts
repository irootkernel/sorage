import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { assertManagedBun, toolchainRoot } from "./toolchain-runtime";

assertManagedBun();

const assetRoot = join(toolchainRoot, "apps/daemon/src/web");
const arguments_ = process.argv.slice(2);
if (arguments_[0] === "--") arguments_.shift();
let check = false;
let outfile = join(toolchainRoot, "apps/daemon/src/web-assets.generated.ts");
while (arguments_.length > 0) {
  const argument = arguments_.shift();
  const outputArgument = arguments_[0];
  if (argument === "--check") {
    check = true;
  } else if (argument === "--out" && outputArgument && !outputArgument.startsWith("--")) {
    outfile = resolve(outputArgument);
    arguments_.shift();
  } else {
    throw new Error("usage: bun run build:web -- [--check] [--out <path>]");
  }
}

// Bun uses the working directory for module comments even with an explicit bundle root.
process.chdir(toolchainRoot);
const result = await Bun.build({
  entrypoints: [join(assetRoot, "main.ts")],
  root: assetRoot,
  target: "browser",
  format: "iife",
  minify: false,
  sourcemap: "none",
});
const [bundle] = result.outputs;
if (!result.success || result.outputs.length !== 1 || bundle === undefined) {
  throw new Error("expected one bundled Web script");
}
const normalize = (text: string) => text.replace(/\r\n/g, "\n");
const html = normalize(readFileSync(join(assetRoot, "index.html"), "utf8"));
const css = normalize(readFileSync(join(assetRoot, "styles.css"), "utf8"));
const script = normalize(await bundle.text());
const expected = Buffer.from(
  [
    "// Generated by scripts/build-web-assets.ts. Do not edit directly.",
    "",
    `export const WEB_INDEX_HTML = ${JSON.stringify(html)};`,
    `export const WEB_CSS = ${JSON.stringify(css)};`,
    `export const WEB_APP_JS = ${JSON.stringify(script)};`,
    "",
  ].join("\n"),
);
if (check) {
  if (!existsSync(outfile) || !readFileSync(outfile).equals(expected)) {
    console.error(`Web asset embedding is missing or stale at ${outfile}. Run bun run build:web to regenerate it.`);
    process.exitCode = 1;
  }
} else {
  writeFileSync(outfile, expected);
}
